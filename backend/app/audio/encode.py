"""Output encoding.

* WAV: PCM16 written directly as RIFF with a ``LIST/INFO`` chunk carrying ``ICMT`` (comment) and
  ``ISFT`` (software) provenance tags.  This is metadata provenance, not a watermark.
* MP3 / FLAC: ffmpeg over a pipe with the same provenance written as the ``comment`` /
  ``encoder`` tags.
"""

from __future__ import annotations

import struct
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from app.engine.config import get_engine_settings
from app.engine.types import AudioBuffer, EngineError, OutputFormat

SOFTWARE_TAG = "PROJECT VOICE"
ENCODE_TIMEOUT_SECONDS = 300


def provenance_comment(generation_id: str) -> str:
    return f"Synthetic speech generated by PROJECT VOICE generation {generation_id}"


@dataclass(frozen=True)
class EncodedFile:
    path: Path
    output_format: OutputFormat
    size_bytes: int
    sample_rate: int
    duration_seconds: float


def to_pcm16(samples: np.ndarray) -> np.ndarray:
    clipped = np.clip(np.asarray(samples, dtype=np.float32), -1.0, 1.0)
    return (clipped * 32767.0).round().astype("<i2")


def _info_chunk(tags: dict[bytes, str]) -> bytes:
    body = b""
    for key, value in tags.items():
        data = value.encode("utf-8") + b"\x00"
        if len(data) % 2:
            data += b"\x00"
        body += key + struct.pack("<I", len(value.encode("utf-8")) + 1) + data
    return b"LIST" + struct.pack("<I", 4 + len(body)) + b"INFO" + body


def write_wav(
    path: Path, buffer: AudioBuffer, *, comment: str, software: str = SOFTWARE_TAG
) -> EncodedFile:
    """PCM16 mono/stereo WAV with ``LIST/INFO`` ICMT + ISFT placed before ``data``."""
    pcm = to_pcm16(buffer.samples)
    channels = 1 if pcm.ndim == 1 else int(pcm.shape[1])
    data = pcm.tobytes()
    if len(data) % 2:
        data += b"\x00"
    byte_rate = buffer.sample_rate * channels * 2
    fmt = b"fmt " + struct.pack(
        "<IHHIIHH", 16, 1, channels, buffer.sample_rate, byte_rate, channels * 2, 16
    )
    info = _info_chunk({b"ICMT": comment, b"ISFT": software})
    data_chunk = b"data" + struct.pack("<I", len(pcm.tobytes())) + data
    riff_body = b"WAVE" + fmt + info + data_chunk
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(b"RIFF" + struct.pack("<I", len(riff_body)) + riff_body)
    return EncodedFile(
        path=path,
        output_format="wav",
        size_bytes=path.stat().st_size,
        sample_rate=buffer.sample_rate,
        duration_seconds=buffer.duration,
    )


def read_wav_info(path: Path) -> dict[str, str]:
    """Parse the ``LIST/INFO`` tags of a RIFF WAV (used by tests and provenance checks)."""
    tags: dict[str, str] = {}
    with open(path, "rb") as fh:
        head = fh.read(12)
        if head[:4] != b"RIFF" or head[8:12] != b"WAVE":
            return tags
        while True:
            header = fh.read(8)
            if len(header) < 8:
                break
            cid, size = header[:4], struct.unpack("<I", header[4:8])[0]
            payload = fh.read(size + (size % 2))
            if cid == b"LIST" and payload[:4] == b"INFO":
                pos = 4
                while pos + 8 <= len(payload):
                    sub, sub_size = (
                        payload[pos : pos + 4],
                        struct.unpack("<I", payload[pos + 4 : pos + 8])[0],
                    )
                    value = (
                        payload[pos + 8 : pos + 8 + sub_size]
                        .rstrip(b"\x00")
                        .decode("utf-8", "replace")
                    )
                    tags[sub.decode("ascii", "replace")] = value
                    pos += 8 + sub_size + (sub_size % 2)
    return tags


def _ffmpeg_encode(
    path: Path, buffer: AudioBuffer, *, codec_args: list[str], comment: str, software: str
) -> None:
    binary = get_engine_settings().FFMPEG_BIN
    cmd = [
        binary, "-v", "error", "-nostdin", "-y",
        "-f", "f32le", "-ar", str(buffer.sample_rate), "-ac", "1", "-i", "pipe:0",
        *codec_args,
        "-metadata", f"comment={comment}",
        "-metadata", f"encoder={software}",
        str(path),
    ]  # fmt: skip
    raw = np.ascontiguousarray(np.clip(buffer.samples, -1.0, 1.0), dtype="<f4").tobytes()
    try:
        proc = subprocess.run(
            cmd, input=raw, capture_output=True, timeout=ENCODE_TIMEOUT_SECONDS, check=False
        )
    except FileNotFoundError as exc:
        raise EngineError(f"ffmpeg binary not found ({binary})", code="ffmpeg_missing") from exc
    except subprocess.TimeoutExpired as exc:
        raise EngineError("ffmpeg timed out while encoding", code="encode_failed") from exc
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip().splitlines()
        raise EngineError(
            f"Encoding failed ({(detail[-1] if detail else 'unknown error')[:200]})",
            code="encode_failed",
        )


def encode(
    buffer: AudioBuffer,
    path: Path,
    *,
    output_format: OutputFormat,
    generation_id: str,
    software: str = SOFTWARE_TAG,
) -> EncodedFile:
    comment = provenance_comment(generation_id)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if output_format == "wav":
        return write_wav(path, buffer, comment=comment, software=software)
    if output_format == "mp3":
        _ffmpeg_encode(
            path,
            buffer,
            codec_args=["-c:a", "libmp3lame", "-q:a", "2", "-id3v2_version", "3"],
            comment=comment,
            software=software,
        )
    elif output_format == "flac":
        _ffmpeg_encode(
            path,
            buffer,
            codec_args=["-c:a", "flac", "-compression_level", "5"],
            comment=comment,
            software=software,
        )
    else:
        raise EngineError(f"Unsupported output format: {output_format}", code="unsupported_format")
    return EncodedFile(
        path=path,
        output_format=output_format,
        size_bytes=path.stat().st_size,
        sample_rate=buffer.sample_rate,
        duration_seconds=buffer.duration,
    )


