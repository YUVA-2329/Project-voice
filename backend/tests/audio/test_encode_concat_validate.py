from tests.engine.support import buffer, speech_like, tone

SR = 24000


def test_wav_round_trip_with_riff_info_provenance(tmp_path: Path) -> None:
    sig = tone(1.0, SR, amplitude=0.5)
    out = encode(buffer(sig, SR), tmp_path / "o.wav", output_format="wav", generation_id="gen-123")
    assert out.output_format == "wav" and out.size_bytes == (tmp_path / "o.wav").stat().st_size
    data, sr = sf.read(str(out.path), dtype="float32")
    assert sr == SR and len(data) == len(sig)
    assert np.max(np.abs(data - sig)) < 1.0 / 32000  # PCM16 quantisation only
    tags = read_wav_info(out.path)
    assert tags["ICMT"] == "Synthetic speech generated by PROJECT VOICE generation gen-123"
    assert tags["ISFT"] == "PROJECT VOICE"
    # ffprobe sees the same tags
    probe = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format_tags",
            "-of",
            "default=nw=1",
            str(out.path),
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    assert "gen-123" in probe.stdout


def test_write_wav_clips_out_of_range_input(tmp_path: Path) -> None:
    hot = tone(0.5, SR, amplitude=1.0) * 1.5
    write_wav(tmp_path / "hot.wav", buffer(hot, SR), comment="c")
    data, _ = sf.read(str(tmp_path / "hot.wav"), dtype="float32")
    assert np.max(np.abs(data)) <= 1.0


@pytest.mark.parametrize("fmt", ["mp3", "flac"])
def test_lossy_and_lossless_encoders_via_ffmpeg(tmp_path: Path, fmt: str) -> None:
    sig = speech_like(1.5, SR)
    out = encode(buffer(sig, SR), tmp_path / f"o.{fmt}", output_format=fmt, generation_id="g-9")  # type: ignore[arg-type]
    assert out.path.is_file() and out.size_bytes > 1000
    data, sr = sf.read(str(out.path), dtype="float32")
    assert sr == SR
    assert abs(len(data) / sr - 1.5) < 0.1
    probe = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format_tags",
            "-of",
            "default=nw=1",
            str(out.path),
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    assert provenance_comment("g-9") in probe.stdout
    if fmt == "flac":
        assert np.max(np.abs(data[: len(sig)] - sig)) < 1e-3  # lossless (24-bit/16-bit rounding)


def test_join_chunks_inserts_pauses_and_crossfades() -> None:
    a = buffer(tone(1.0, SR, amplitude=0.5), SR)
    b = buffer(tone(1.0, SR, amplitude=0.5), SR)
    c = buffer(tone(0.5, SR, amplitude=0.5), SR)
    joined = join_chunks([a, b, c], [300, 0, 0])
    # a + 0.3 s + b crossfaded with c (20 ms overlap)
    expected = 1.0 + 0.3 + 1.0 + 0.5 - 0.02
    assert abs(joined.duration - expected) < 0.005
    pause = joined.samples[int(1.0 * SR) + 200 : int(1.3 * SR) - 200]
    assert np.max(np.abs(pause)) == 0.0
    assert np.max(np.abs(joined.samples)) <= 0.5 + 1e-6  # crossfade does not overshoot
    tail = join_chunks([a], [250])
    assert abs(tail.duration - 1.25) < 1e-3


def test_crossfade_is_equal_power() -> None:
    a = np.ones(1000, dtype=np.float32)
    b = np.ones(1000, dtype=np.float32)
    out = crossfade(a, b, 10000, fade_ms=50)
    assert len(out) == 1500
    mid = out[500:1000]
    # sin+cos of same-sign signals peaks at sqrt(2) in the middle; never below 1
    assert np.min(mid) >= 1.0 - 1e-5 and np.max(mid) <= np.sqrt(2) + 1e-5


def test_join_chunks_argument_errors() -> None:
    with pytest.raises(ValueError):
        join_chunks([], [])
    with pytest.raises(ValueError):
        join_chunks([buffer(tone(0.1, SR), SR)], [0, 0])


def test_validate_output_accepts_plausible_audio() -> None:
    text = "This is a reasonably long English sentence for validation purposes."
    expected = expected_duration(text, Language.EN)
    sig = speech_like(expected, SR)
    report = validate_output(buffer(sig, SR), text=text, language=Language.EN)
    assert report.ok, report
    assert report.errors == []


def test_validate_output_rejects_nan_silence_and_implausible_duration() -> None:
    text = "This is a reasonably long English sentence for validation purposes."
    nan = np.full(SR, np.nan, dtype=np.float32)
    assert "NaN" in validate_output(buffer(nan, SR), text=text, language=Language.EN).errors[0]
    silent = validate_output(
        buffer(np.zeros(SR * 5, dtype=np.float32), SR), text=text, language=Language.EN
    )
    assert any("silence" in e for e in silent.errors)
    tiny = validate_output(buffer(speech_like(0.3, SR), SR), text=text, language=Language.EN)
    assert any("short" in e for e in tiny.errors)
    huge = validate_output(buffer(speech_like(60.0, SR), SR), text="Hi.", language=Language.EN)
    assert any("long" in e for e in huge.errors)
    clipped = validate_output(
        buffer(np.clip(speech_like(5.0, SR) * 10, -1, 1), SR), text=text, language=Language.EN
    )
    assert any("clipped" in e for e in clipped.errors)


def test_silence_ratio_and_expected_duration_by_script() -> None:
    half = np.concatenate([np.zeros(SR, dtype=np.float32), tone(1.0, SR, amplitude=0.5)])
    assert abs(silence_ratio(buffer(half, SR)) - 0.5) < 0.02
    assert expected_duration("你好世界", Language.ZH) > expected_duration("abcd", Language.EN)
    assert expected_duration("", None) >= 0.3
