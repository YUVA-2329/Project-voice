"""Real end-to-end model tests: ZipVoice + Whisper + Silero through ``VoicePipeline``.

Reference: ``models/zipvoice-distill/test_wavs/leijun-1.wav`` (Chinese, ~6 s).  The tests create
a voice from it (decode → analyse → VAD → trim → transcribe → validate → fingerprint), synthesise
English, Chinese and a multi-chunk English paragraph, check the WAVs, and close the loop with an
ASR round trip.  Passing tests record verification evidence that turns ZipVoice ``en``/``zh``
to ``verified`` in ``VoicePipeline.language_matrix()`` for this deployment.
"""

