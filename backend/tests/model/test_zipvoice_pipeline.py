def _han_overlap(reference: str, hypothesis: str) -> float:
    ref = [ch for ch in reference if count_scripts(ch).get("Han")]
    hyp = [ch for ch in hypothesis if count_scripts(ch).get("Han")]
    if not ref:
        return 0.0
    remaining = list(hyp)
    hits = 0
    for ch in ref:
        if ch in remaining:
            remaining.remove(ch)
            hits += 1
    return hits / len(ref)


def _load_wav(path: Path) -> AudioBuffer:
    data, sr = sf.read(str(path), dtype="float32")
    assert data.ndim == 1, "output must be mono"
    return AudioBuffer(samples=data, sample_rate=sr)


def _check_output(
    outcome: SynthesisOutcome, text: str, language: Language, *, min_chunks: int = 1
) -> AudioBuffer:
    assert outcome.output_path.is_file()
    assert outcome.engine_id == "zipvoice_distill"
    assert outcome.language == language
    assert outcome.device == "cpu"
    assert outcome.chunks >= min_chunks
    audio = _load_wav(outcome.output_path)
    assert audio.sample_rate == 24000 and outcome.sample_rate == 24000
    assert abs(audio.duration - outcome.duration_seconds) < 0.01
    expected = expected_duration(text, language)
    assert 0.3 * expected <= audio.duration <= 3.0 * expected + 1.0, (audio.duration, expected)
    assert np.all(np.isfinite(audio.samples))
    assert peak_dbfs(audio.samples) <= -0.9, peak_dbfs(audio.samples)
    assert abs(outcome.peak_dbfs - peak_dbfs(audio.samples)) < 0.1
    assert outcome.clipping_ratio == 0.0
    tags = read_wav_info(outcome.output_path)
    assert tags["ISFT"] == "PROJECT VOICE"
    assert "Synthetic speech generated by PROJECT VOICE generation" in tags["ICMT"]
    assert outcome.inference_seconds > 0 and outcome.total_seconds >= outcome.inference_seconds
    assert outcome.real_time_factor > 0
    return audio


@pytest.fixture(scope="module")
def voice(pipeline, work_root: Path) -> VoiceCreationResult:  # type: ignore[no-untyped-def]
    stages: list[tuple[str, int, int]] = []
    started = time.perf_counter()
    result = pipeline.create_voice(
        LEIJUN_WAV,
        language_hint=None,
        user_transcript=None,
        work_dir=work_root / "voice",
        progress=lambda s, c, t: stages.append((s, c, t)),
    )
    TIMINGS["create_voice"] = {
        "seconds": round(time.perf_counter() - started, 2),
        "reference_seconds": round(result.reference_duration_seconds, 2),
        "transcript": result.transcript,
    }
    reported = [s for s, _c, _t in stages]
    for stage in ("decode", "analyse", "vad", "trim", "transcribe", "validate", "fingerprint"):
        assert stage in reported, reported
    return result


def test_create_voice_from_chinese_reference(voice: VoiceCreationResult) -> None:
    assert voice.processed_path.is_file()
    processed = _load_wav(voice.processed_path)
    assert processed.sample_rate == 24000
    assert 3.0 <= processed.duration <= 30.0
    assert 5.0 <= processed.duration <= 6.2  # the clip is ~6.06 s of continuous speech
    assert abs(peak_dbfs(processed.samples) - (-1.0)) < 0.05  # peak-normalised to -1 dBFS
    assert voice.engine_id == "zipvoice_distill"
    assert voice.transcript_source == "auto"
    assert voice.detected_language == Language.ZH and voice.language == Language.ZH
    assert voice.transcript
    overlap = _han_overlap(LEIJUN_TRANSCRIPT, voice.transcript)
    assert overlap >= 0.5, (voice.transcript, overlap)
    assert voice.fingerprint is not None and voice.fingerprint.engine_id == "zipvoice_distill"
    assert voice.fingerprint.data["kind"] == "reference_conditioning"
    assert voice.analysis.speech_seconds > 4.0
    assert voice.analysis.clipping_ratio == 0.0
    TIMINGS["create_voice"]["transcript_han_overlap"] = round(overlap, 3)


def test_synthesize_english_and_asr_round_trip(
    pipeline, voice: VoiceCreationResult, work_root: Path
) -> None:  # type: ignore[no-untyped-def]
    """Synthesise English from the Chinese reference and check intelligibility by ASR.

    ZipVoice samples a new noise trajectory every call and whisper-base (int8) is a weak judge of
    accented speech, so the round trip is allowed up to ``ASR_MAX_ATTEMPTS`` fresh samples; every
    attempt is recorded in the verification evidence.
    """
    attempts: list[dict[str, object]] = []
    best: tuple[float, SynthesisOutcome, str] | None = None
    for attempt in range(ASR_MAX_ATTEMPTS):
        progress: list[tuple[str, int, int]] = []
        outcome = pipeline.synthesize(
            text=ENGLISH_SENTENCE,
            language="auto",
            reference_path=voice.processed_path,
            reference_transcript=voice.transcript,
            reference_language=voice.language,
            engine_id=None,
            speed=1.0,
            quality="fast",
            output_format="wav",
            work_dir=work_root / f"en-{attempt}",
            generation_id=f"test-en-{attempt}",
            progress=lambda s, c, t, _p=progress: _p.append((s, c, t)),
        )
        audio = _check_output(outcome, ENGLISH_SENTENCE, Language.EN)
        assert outcome.details["cross_lingual"] is True  # zh reference → en output
        stages = [s for s, _c, _t in progress]
        for stage in ("prepare", "load_model", "synthesize", "encode", "validate"):
            assert stage in stages
        assert ("synthesize", outcome.chunks, outcome.chunks) in progress

        started = time.perf_counter()
        text, lang = pipeline.transcriber.transcribe(resample(audio, 16000).samples, Language.EN)
        asr_seconds = time.perf_counter() - started
        assert lang == Language.EN
        overlap = word_overlap(ENGLISH_SENTENCE, text)
        attempts.append(
            {
                "attempt": attempt + 1,
                "inference_seconds": round(outcome.inference_seconds, 2),
                "total_seconds": round(outcome.total_seconds, 2),
                "audio_seconds": round(outcome.duration_seconds, 2),
                "rtf": round(outcome.real_time_factor, 3),
                "peak_dbfs": round(outcome.peak_dbfs, 2),
                "asr_seconds": round(asr_seconds, 2),
                "asr_text": text,
                "asr_word_overlap": round(overlap, 3),
            }
        )
        if best is None or overlap > best[0]:
            best = (overlap, outcome, text)
        if overlap >= 0.6:
            break
    assert best is not None
    TIMINGS["synthesize_en"] = {"attempts": attempts, "best_overlap": round(best[0], 3)}
    assert best[0] >= 0.6, attempts
    pipeline.record_verification(
        "zipvoice_distill",
        Language.EN,
        {
            "rtf": best[1].real_time_factor,
            "asr_overlap": best[0],
            "asr_attempts": len(attempts),
            "asr_overlaps": [a["asr_word_overlap"] for a in attempts],
            "quality": "fast",
            "test": "tests/model/test_zipvoice_pipeline.py::"
            "test_synthesize_english_and_asr_round_trip",
        },
    )


# Whisper often emits traditional forms for Mandarin; map the variants in CHINESE_SENTENCE.
_TRAD_TO_SIMP = str.maketrans("氣們決著邊計劃沿聊", "气们决着边计划沿聊")


def test_synthesize_chinese(pipeline, voice: VoiceCreationResult, work_root: Path) -> None:  # type: ignore[no-untyped-def]
    attempts: list[dict[str, object]] = []
    best: tuple[float, SynthesisOutcome, str] | None = None
    for attempt in range(ASR_MAX_ATTEMPTS):
        outcome = pipeline.synthesize(
            text=CHINESE_SENTENCE,
            language=Language.ZH,
            reference_path=voice.processed_path,
            reference_transcript=voice.transcript,
            reference_language=voice.language,
            engine_id="zipvoice_distill",
            speed=1.0,
            quality="balanced",
            output_format="wav",
            work_dir=work_root / f"zh-{attempt}",
            generation_id=f"test-zh-{attempt}",
        )
        audio = _check_output(outcome, CHINESE_SENTENCE, Language.ZH)
        assert outcome.details["chunks"][0]["num_steps"] == 8
        assert outcome.details["cross_lingual"] is False
        text, lang = pipeline.transcriber.transcribe(resample(audio, 16000).samples, Language.ZH)
        assert lang == Language.ZH
        overlap = _han_overlap(CHINESE_SENTENCE, text.translate(_TRAD_TO_SIMP))
        attempts.append(
            {
                "attempt": attempt + 1,
                "inference_seconds": round(outcome.inference_seconds, 2),
                "audio_seconds": round(outcome.duration_seconds, 2),
                "rtf": round(outcome.real_time_factor, 3),
                "peak_dbfs": round(outcome.peak_dbfs, 2),
                "asr_text": text,
                "asr_han_overlap": round(overlap, 3),
            }
        )
        if best is None or overlap > best[0]:
            best = (overlap, outcome, text)
        if overlap >= 0.5:
            break
    assert best is not None
    TIMINGS["synthesize_zh"] = {"attempts": attempts, "best_overlap": round(best[0], 3)}
    assert best[0] >= 0.5, attempts
    pipeline.record_verification(
        "zipvoice_distill",
        Language.ZH,
        {
            "rtf": best[1].real_time_factor,
            "asr_overlap": best[0],
            "asr_attempts": len(attempts),
            "asr_overlaps": [a["asr_han_overlap"] for a in attempts],
            "quality": "balanced",
            "test": "tests/model/test_zipvoice_pipeline.py::test_synthesize_chinese",
        },
    )


def test_long_english_paragraph_is_chunked_and_joined(
    pipeline, voice: VoiceCreationResult, work_root: Path
) -> None:  # type: ignore[no-untyped-def]
    progress: list[tuple[str, int, int]] = []
    outcome = pipeline.synthesize(
        text=LONG_ENGLISH,
        language=Language.EN,
        reference_path=voice.processed_path,
        reference_transcript=voice.transcript,
        reference_language=voice.language,
        engine_id=None,
        speed=1.0,
        quality="fast",
        output_format="wav",
        work_dir=work_root / "long",
        generation_id="test-long",
        progress=lambda s, c, t: progress.append((s, c, t)),
    )
    audio = _check_output(outcome, LONG_ENGLISH, Language.EN, min_chunks=3)
    synth_steps = [(c, t) for s, c, t in progress if s == "synthesize"]
    assert synth_steps[0] == (0, outcome.chunks) and synth_steps[-1] == (
        outcome.chunks,
        outcome.chunks,
    )
    assert len(outcome.details["chunks"]) == outcome.chunks
    assert sum(c["seconds"] for c in outcome.details["chunks"]) <= audio.duration + 0.5
    TIMINGS["synthesize_long_en"] = {
        "chunks": outcome.chunks,
        "chars": len(LONG_ENGLISH),
        "inference_seconds": round(outcome.inference_seconds, 2),
        "total_seconds": round(outcome.total_seconds, 2),
        "audio_seconds": round(outcome.duration_seconds, 2),
        "rtf": round(outcome.real_time_factor, 3),
        "peak_dbfs": round(outcome.peak_dbfs, 2),
    }


def test_mp3_output_and_speed(pipeline, voice: VoiceCreationResult, work_root: Path) -> None:  # type: ignore[no-untyped-def]
    outcome = pipeline.synthesize(
        text="Hello there, this is a quick check.",
        language=Language.EN,
        reference_path=voice.processed_path,
        reference_transcript=voice.transcript,
        reference_language=voice.language,
        engine_id=None,
        speed=1.2,
        quality="fast",
        output_format="mp3",
        work_dir=work_root / "mp3",
        generation_id="test-mp3",
    )
    assert outcome.output_format == "mp3" and outcome.output_path.suffix == ".mp3"
    data, sr = sf.read(str(outcome.output_path), dtype="float32")
